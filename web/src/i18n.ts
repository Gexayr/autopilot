const DICTS: Record<Lang, Dict> = { ru, en, hy };
const STORE_KEY = 'autopilot.lang';

function detect(): Lang {
  try {
    const saved = localStorage.getItem(STORE_KEY);
    if (saved === 'ru' || saved === 'en' || saved === 'hy') return saved;
  } catch { /* private mode */ }
  const code = ((window as any).Telegram?.WebApp?.initDataUnsafe?.user?.language_code as string | undefined) ?? navigator.language ?? '';
  if (/^hy/i.test(code)) return 'hy';
  if (/^en/i.test(code)) return 'en';
  return 'ru';
}

let current: Lang = detect();
dayjs.locale(DAYJS_LOCALE[current]);
document.documentElement.lang = current;

export const lang = () => current;


/** The same text in every language (e.g. to recognise a preset written in another UI language). */
export const variants = (key: Key) => Object.values(DICTS).map((d) => d[key] as string);

/** Switch the language; the app re-renders from the root (see I18nRoot in main.tsx). */
export function setLang(l: Lang) {
  current = l;
  dayjs.locale(DAYJS_LOCALE[l]);
  document.documentElement.lang = l;
  try { localStorage.setItem(STORE_KEY, l); } catch { /* private mode */ }
  listeners.forEach((fn) => fn(l));
}
const listeners = new Set<(l: Lang) => void>();
export const onLangChange = (fn: (l: Lang) => void) => { listeners.add(fn); return () => listeners.delete(fn); };

const fill = (s: string, vars?: Record<string, string | number>) =>
  vars ? s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m)) : s;

export function t(key: Key, vars?: Record<string, string | number>): string {
  const v = DICTS[current][key] ?? ru[key];
  return fill(Array.isArray(v) ? v[0] : (v as string), vars);
}

/** Plural form for `n` ({n} is filled in). */
export function tn(key: Key, n: number, vars?: Record<string, string | number>): string {
  const v = DICTS[current][key] ?? ru[key];
  const forms = Array.isArray(v) ? v : [v as string];
  const cat = new Intl.PluralRules(NUMBER_LOCALE[current]).select(n);
  const idx = current === 'ru' ? ({ one: 0, few: 1 } as Record<string, number>)[cat] ?? 2 : cat === 'one' ? 0 : 1;
  return fill(forms[Math.min(idx, forms.length - 1)], { n, ...vars });
}
